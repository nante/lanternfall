import { artFamilies, type ArtFamily, type ArtSlot } from '../../../packages/game/src/art-slots.ts';
import { generatedPixels } from '../../client/src/render/textures.ts';
import type { View } from './balance.ts';
import { h, toast, fill } from './ui.ts';
import { decodePng, encodePng, download, pickFile, type Rgba } from './png.ts';

type SlotState = ArtSlot & { revision: string | null };
const drafts = new Map<string, { image: Rgba; name: string }>();
const savedCache = new Map<string, { revision: string; image: Rgba }>();

function paint(canvas: HTMLCanvasElement, img: Rgba, scale: number, tiles = 1) {
  canvas.width = img.width * scale * tiles; canvas.height = img.height * scale * tiles;
  const g = canvas.getContext('2d')!;
  g.imageSmoothingEnabled = false;
  const src = new OffscreenCanvas(img.width, img.height);
  src.getContext('2d')!.putImageData(new ImageData(new Uint8ClampedArray(img.data), img.width, img.height), 0, 0);
  for (let ty = 0; ty < tiles; ty++) for (let tx = 0; tx < tiles; tx++) g.drawImage(src, tx * img.width * scale, ty * img.height * scale, img.width * scale, img.height * scale);
}
async function savedImage(slot: SlotState): Promise<Rgba | null> {
  if (!slot.revision) return null;
  const hit = savedCache.get(slot.id);
  if (hit?.revision === slot.revision) return hit.image;
  const res = await fetch(`/api/art/${slot.id}`);
  if (!res.ok) return null;
  const image = await decodePng(await res.blob());
  savedCache.set(slot.id, { revision: slot.revision, image });
  return image;
}

export function texturesView(ctx: { selected: string | null; select: (id: string) => void }): View {
  let slots: SlotState[] = [];
  const list = h('nav', { class: 'list' });
  const detail = h('section', { class: 'detail' });
  const aside = h('section', { class: 'derived' });
  let alive = true;

  const refresh = async () => {
    slots = await (await fetch('/api/art')).json() as SlotState[];
    if (!alive) return;
    drawList(); await drawDetail();
  };
  const current = () => slots.find(s => s.id === ctx.selected) ?? slots[0];

  const drawList = () => {
    const ul = h('ul', { class: 'records', role: 'listbox', 'aria-label': 'Texture slots' });
    let family = '';
    for (const s of slots) {
      if (s.family !== family) { family = s.family; ul.append(h('li', { class: 'group', role: 'presentation' }, `${family[0].toUpperCase()}${family.slice(1)} · ${artFamilies[family as ArtFamily].width}×${artFamilies[family as ArtFamily].height}`)); }
      const thumb = h('canvas', { class: 'thumb', 'aria-hidden': 'true' });
      const img = drafts.get(s.id)?.image ?? savedCache.get(s.id)?.image ?? generatedPixels(s.id);
      paint(thumb, img, 1);
      ul.append(h('li', { role: 'option', 'aria-selected': s === current(), tabindex: s === current() ? 0 : -1, onclick: () => ctx.select(s.id) },
        thumb, h('span', { class: 'lbl' }, s.kind), h('span', { class: `sub tag ${drafts.has(s.id) ? 'draft' : s.revision ? 'png' : ''}` }, drafts.has(s.id) ? 'Unsaved' : s.revision ? 'Hand-made' : 'Generated')));
    }
    list.replaceChildren(ul);
  };

  const drawDetail = async () => {
    const s = current(); if (!s) return;
    const draft = drafts.get(s.id), saved = await savedImage(s), generated = generatedPixels(s.id);
    if (!alive || s !== current()) return;
    const shown = draft?.image ?? saved ?? generated;
    const scale = Math.max(1, Math.floor(320 / Math.max(s.width, s.height)));
    const raw = h('canvas', { class: 'pixels', 'aria-label': `${s.id} at ${scale}× zoom` });
    const tiled = h('canvas', { class: 'pixels', 'aria-label': `${s.id} repeated 3 by 3` });
    paint(raw, shown, scale); paint(tiled, shown, Math.max(1, Math.floor(scale / 2)), 3);
    const source = draft ? `Unsaved import: ${draft.name}` : saved ? `Hand-made PNG · content/${s.path}` : 'Generated by code (no PNG yet)';
    fill(detail, h('div', { class: 'form' },
      h('header', { class: 'record-head' }, h('div', {}, h('h2', {}, s.id), h('p', { class: 'muted' }, `${s.width}×${s.height} px · ${artFamilies[s.family].note}`))),
      h('p', { class: `source ${draft ? 'draft' : saved ? 'png' : ''}` }, source),
      h('div', { class: 'toolbar' },
        h('button', { class: 'ghost', onclick: () => importInto(s) }, 'Import PNG'),
        h('button', { class: 'ghost', onclick: async () => download(await encodePng(shown), `${s.family}-${s.kind}.png`) }, 'Export shown'),
        h('button', { class: 'ghost', onclick: async () => download(await encodePng(generated), `${s.family}-${s.kind}-generated.png`), title: 'A starting point to paint over in Aseprite or another editor' }, 'Export generated'),
        h('span', { class: 'spacer' }),
        draft ? h('button', { class: 'ghost', onclick: () => { drafts.delete(s.id); drawList(); drawDetail(); } }, 'Discard') : null,
        !draft && s.revision ? h('button', { class: 'ghost', onclick: () => useGenerated(s) }, 'Use generated') : null,
        h('button', { class: 'primary', disabled: !draft, onclick: () => save(s) }, 'Save')),
      h('div', { class: 'canvas-wrap' }, raw),
      h('p', { class: 'hint-row' }, `Paint at ${s.width}×${s.height}, fully opaque. ${s.family === 'ground' ? 'The image covers 2×2 world tiles and must tile seamlessly on all edges.' : 'The image repeats along the surface.'} After saving, reload the game to see it under the real lighting.`)));
    fill(aside, h('h3', {}, 'Tiled 3×3'), h('div', { class: 'canvas-wrap small' }, tiled),
      saved && draft ? [h('h3', {}, 'Currently saved'), (() => { const c = h('canvas', { class: 'pixels' }); paint(c, saved, Math.max(1, Math.floor(scale / 2))); return h('div', { class: 'canvas-wrap small' }, c); })()] : null,
      h('h3', {}, 'Generated'), (() => { const c = h('canvas', { class: 'pixels' }); paint(c, generated, Math.max(1, Math.floor(scale / 2))); return h('div', { class: 'canvas-wrap small' }, c); })());
  };

  const importInto = async (s: SlotState) => {
    const file = await pickFile(); if (!file) return;
    try {
      const image = await decodePng(file);
      if (image.width !== s.width || image.height !== s.height) throw new Error(`${file.name} is ${image.width}×${image.height}; ${s.id} needs exactly ${s.width}×${s.height}. Resize the canvas, do not scale the art.`);
      for (let i = 3; i < image.data.length; i += 4) if (image.data[i] !== 255) throw new Error('Textures must be fully opaque. Flatten the image onto a solid background.');
      drafts.set(s.id, { image, name: file.name });
      drawList(); drawDetail();
    } catch (e) { toast((e as Error).message, 'error'); }
  };
  const save = async (s: SlotState) => {
    const draft = drafts.get(s.id); if (!draft) return;
    const res = await fetch(`/api/art/${s.id}`, { method: 'PUT', headers: { 'content-type': 'image/png', 'x-expected-revision': s.revision ?? 'none' }, body: await encodePng(draft.image) });
    const body = await res.json() as { message?: string };
    if (!res.ok) { toast(body.message ?? 'Save failed.', 'error'); if (res.status === 409) refresh(); return; }
    drafts.delete(s.id); savedCache.delete(s.id);
    toast(`Saved content/${s.path}. Reload the game to see it.`, 'ok');
    refresh();
  };
  const useGenerated = async (s: SlotState) => {
    if (!confirm(`Remove the hand-made ${s.id} texture and go back to the generated one? The PNG is kept in .local/studio-backups.`)) return;
    const res = await fetch(`/api/art/${s.id}`, { method: 'DELETE', headers: { 'x-expected-revision': s.revision ?? 'none' } });
    if (!res.ok) { toast(((await res.json()) as { message?: string }).message ?? 'Could not remove it.', 'error'); return; }
    savedCache.delete(s.id); toast(`${s.id} uses the generated texture again.`, 'ok'); refresh();
  };

  const onArt = () => { refresh(); };
  addEventListener('studio:art-changed', onArt);
  refresh();
  return { el: h('div', { class: 'split three textures' }, list, detail, aside), destroy: () => { alive = false; removeEventListener('studio:art-changed', onArt); } };
}

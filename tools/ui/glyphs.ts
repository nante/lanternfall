// Lanternfall's pixel lettering, drawn on a grid. Each glyph lists its rows from the cap line (y = 6) down to the
// baseline row (y = 0), then up to two descender rows. `#` is ink. Capitals are 7 tall, small letters 5 with
// 2-row ascenders and descenders, digits share one width so numbers line up. Accented letters are composed from a
// base and a mark (below), so every diacritic sits the same way on every letter.
